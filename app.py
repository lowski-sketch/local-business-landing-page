@app.route("/api/admin/providers", methods=["GET"])
@require_admin_token
def get_provider_applications():
    database_url = os.environ.get("DATABASE_URL")

    if database_url:
        with psycopg.connect(database_url) as connection:
            cursor = connection.execute("""
                SELECT
                    id,
                    business_name,
                    contact_name,
                    email,
                    phone,
                    business_address,
                    service_area,
                    services,
                    customer_types,
                    years_in_business,
                    insurance_info,
                    license_info,
                    website,
                    availability,
                    status,
                    created_at
                FROM provider_applications
                ORDER BY created_at DESC
            """)

            columns = [column.name for column in cursor.description]
            applications = [
                dict(zip(columns, row))
                for row in cursor.fetchall()
            ]
    else:
        connection = sqlite3.connect(DATABASE)
        connection.row_factory = sqlite3.Row

        try:
            rows = connection.execute("""
                SELECT *
                FROM provider_applications
                ORDER BY created_at DESC
            """).fetchall()

            applications = [dict(row) for row in rows]
        finally:
            connection.close()

    for application in applications:
        if application.get("created_at") is not None:
            application["created_at"] = str(application["created_at"])

    return jsonify({"applications": applications}), 200
@app.route("/api/admin/providers/<int:application_id>/status", methods=["PATCH"])
@require_admin_token
def update_provider_status(application_id):
    data = request.get_json(silent=True)

    if not isinstance(data, dict):
        return jsonify({"error": "Please send a valid JSON request."}), 400

    new_status = data.get("status")

    if new_status not in ("approved", "rejected"):
        return jsonify({
            "error": "Status must be approved or rejected."
        }), 400

    database_url = os.environ.get("DATABASE_URL")

    if database_url:
        with psycopg.connect(database_url) as connection:
            cursor = connection.execute("""
                UPDATE provider_applications
                SET status = %s
                WHERE id = %s
                RETURNING id, business_name, status
            """, (new_status, application_id))

            row = cursor.fetchone()

            if row is None:
                return jsonify({
                    "error": "Provider application not found."
                }), 404

            result = {
                "id": row[0],
                "business_name": row[1],
                "status": row[2]
            }
    else:
        connection = sqlite3.connect(DATABASE)
        connection.row_factory = sqlite3.Row

        try:
            cursor = connection.execute("""
                UPDATE provider_applications
                SET status = ?
                WHERE id = ?
            """, (new_status, application_id))

            if cursor.rowcount == 0:
                return jsonify({
                    "error": "Provider application not found."
                }), 404

            connection.commit()

            row = connection.execute("""
                SELECT id, business_name, status
                FROM provider_applications
                WHERE id = ?
            """, (application_id,)).fetchone()

            result = dict(row)
        finally:
            connection.close()

    return jsonify({
        "message": f"Provider application {new_status}.",
        "application": result
    }), 200
